add('tolerance_stack','Dimensional tolerances, stack-ups and manufacturing variation',
'''An assembly can fail to fit even when each part looks close to nominal. Tolerance stacks accumulate dimensional variation along a functional path. Worst-case addition provides a deterministic bound under bounded independent specifications, while root-sum-square estimates rely on statistical assumptions. Manufacturing bias and correlation can invalidate the reassuring statistical result. This laboratory compares both calculations with seeded manufactured samples and makes the probability model explicit.''',
'worst_case=sum(abs(t_i)); RSS=sqrt(sum(sigma_i^2)); assembly_error=sum(component_errors).',
r'''
def experiment(p):
    rng=np.random.default_rng(83);n=20000
    sigma=np.array([.02,.03,.015])*p['scale']
    correlation=p['correlation']
    common=rng.normal(0,1,(n,1));independent=rng.normal(0,1,(n,3))
    errors=sigma*(np.sqrt(correlation)*common+np.sqrt(1-correlation)*independent)
    total=errors.sum(axis=1)
    assumed_independent=np.sqrt(np.sum(sigma**2))
    worst=3*sigma.sum()
    metrics=dict(independent_RSS_std_mm=assumed_independent,empirical_std_mm=np.std(total),
        three_sigma_worst_case_mm=worst,fit_violation_fraction=np.mean(abs(total)>.15),
        empirical_95_percentile_abs_mm=np.quantile(abs(total),.95))
    derivation=[f'Component standard deviations are {sigma.tolist()} mm.',
        f'Use pairwise correlation generated by a common factor with rho={correlation:g}.',
        f'Independent RSS prediction is {assumed_independent:.6f} mm.',
        f'Empirical stack standard deviation is {np.std(total):.6f} mm.',
        f'Against an illustrative +/-0.15 mm assembly window, violation fraction is {metrics["fit_violation_fraction"]:.6f}.']
    notes=['The three-sigma sum is a bounded-specification illustration, not an absolute bound for unbounded Gaussian samples.',
           'Actual drawing tolerances, process capability, datum strategy and measurement uncertainty determine the proper analysis.']
    return metrics,derivation,notes
''',dict(scale=1.,correlation=.0),'correlation',[0.,.1,.25,.5,.75,1.],
'scale multiplies component dimensional standard deviations; correlation is the nonnegative common-factor fraction.',
'Correlated errors are constructed from shared and independent Gaussian factors. Compare empirical variability with the RSS assumption before using the statistical result for fit decisions.',
'Treating drawing limits as Gaussian sigma; ignoring common fixture bias; mixing dimensions from inconsistent datums.',
['Add a systematic machining offset to all parts.','Replace Gaussian errors with bounded uniform errors.','Include instrument uncertainty in acceptance decisions.'],
'Critical bearing, shaft and fastener fits must follow approved drawings and inspection procedures; the example window is not an Asimov tolerance.')

