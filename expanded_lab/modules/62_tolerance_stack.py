"""Dimensional tolerances, stack-ups and manufacturing variation. Numerical teaching experiment only."""

import math
import json
import argparse
import numpy as np


def experiment(p):
    rng = np.random.default_rng(83)
    n = 20000
    sigma = np.array([0.02, 0.03, 0.015]) * p["scale"]
    correlation = p["correlation"]
    common = rng.normal(0, 1, (n, 1))
    independent = rng.normal(0, 1, (n, 3))
    errors = sigma * (
        np.sqrt(correlation) * common + np.sqrt(1 - correlation) * independent
    )
    total = errors.sum(axis=1)
    assumed_independent = np.sqrt(np.sum(sigma**2))
    worst = 3 * sigma.sum()
    metrics = dict(
        independent_RSS_std_mm=assumed_independent,
        empirical_std_mm=np.std(total),
        three_sigma_worst_case_mm=worst,
        fit_violation_fraction=np.mean(abs(total) > 0.15),
        empirical_95_percentile_abs_mm=np.quantile(abs(total), 0.95),
    )
    derivation = [
        f"Component standard deviations are {sigma.tolist()} mm.",
        f"Use pairwise correlation generated by a common factor with rho={correlation:g}.",
        f"Independent RSS prediction is {assumed_independent:.6f} mm.",
        f"Empirical stack standard deviation is {np.std(total):.6f} mm.",
        f'Against an illustrative +/-0.15 mm assembly window, violation fraction is {metrics["fit_violation_fraction"]:.6f}.',
    ]
    notes = [
        "The three-sigma sum is a bounded-specification illustration, not an absolute bound for unbounded Gaussian samples.",
        "Actual drawing tolerances, process capability, datum strategy and measurement uncertainty determine the proper analysis.",
    ]
    return metrics, derivation, notes


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--case", type=int, default=0, choices=range(6))
    args = parser.parse_args()
    parameters = {"scale": 1.0, "correlation": 0.0}
    parameters["correlation"] = [0.0, 0.1, 0.25, 0.5, 0.75, 1.0][args.case]
    metrics, derivation, notes = experiment(parameters)
    result = dict(
        parameters=parameters,
        metrics={k: float(v) for k, v in metrics.items()},
        derivation=derivation,
        notes=notes,
    )
    print(json.dumps(result, indent=2))
