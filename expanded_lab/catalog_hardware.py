add('hysteresis_calibration','Bidirectional calibration and hidden hysteresis',
'''A sensor calibration fitted in one direction may fail on reversal. Backlash, friction and structural compliance can create direction-dependent observations that a single scale-and-offset model cannot represent. The correct response is to expose the residual structure rather than silently widen a tolerance. This experiment generates forward and reverse measurements with a known hysteresis term, fits a shared linear calibration and quantifies the remaining directional bias.''',
'measurement=a*reference+b+direction*hysteresis+noise; a shared fit cannot remove opposite signed direction offsets.',
r'''
def experiment(p):
    rng=np.random.default_rng(89);x=np.linspace(-.5,.5,100)
    h=p['hysteresis'];a,b=1.02,.01
    forward=a*x+b+h+rng.normal(0,.001,len(x))
    reverse=a*x+b-h+rng.normal(0,.001,len(x))
    X=np.column_stack([np.tile(x,2),np.ones(200)])
    y=np.concatenate([forward,reverse])
    theta=np.linalg.lstsq(X,y,rcond=None)[0]
    residual=y-X@theta
    f_bias=residual[:100].mean();r_bias=residual[100:].mean()
    metrics=dict(fitted_scale=theta[0],fitted_offset_rad=theta[1],
        pooled_residual_rmse_rad=np.sqrt(np.mean(residual**2)),
        forward_bias_rad=f_bias,reverse_bias_rad=r_bias,
        directional_separation_rad=f_bias-r_bias)
    derivation=[f'True scale is {a:g} and offset {b:g} rad.',
        f'Add directional offset +/-{h:g} rad and 0.001 rad noise.',
        f'Fit one shared scale/offset to both directions: {theta.tolist()}.',
        f'Forward residual mean is {f_bias:.6f} rad; reverse mean is {r_bias:.6f} rad.',
        f'Directional separation is {f_bias-r_bias:.6f} rad, revealing structure hidden by a pooled fit.']
    notes=['A low aggregate fit error can still conceal a consistent direction-dependent error relevant to reaching or balance.',
           'A calibration model should match the phenomenon and be validated on independent bidirectional trajectories.']
    return metrics,derivation,notes
''',dict(hysteresis=.005),'hysteresis',[0.,.001,.002,.005,.01,.02],
'hysteresis is the signed measurement offset magnitude in radians for forward versus reverse motion.',
'Preserve direction labels during data collection. A residual-versus-direction comparison distinguishes hysteresis from ordinary zero-mean measurement noise.',
'Fitting only one sweep direction; treating backlash as a fixed zero offset; using the same calibration trajectories as final validation.',
['Fit an explicit direction-dependent term and compare held-out residuals.','Add temperature dependence and test a two-factor model.','Detect reversals from velocity with a deadband.'],
'Joint and ankle calibration should include reversals, load conditions and temperature ranges relevant to the intended physical skill.')

